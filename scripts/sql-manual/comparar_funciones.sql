    and a.attnum > 0 and not a.attisdropped
)
select coalesce(e.columna, r.columna) as columna,
       case when r.columna is null then 'no existe en produccion'
            when e.columna is null then 'sobra en produccion (no esta en el repo)'
            else 'distinta (tipo, nulabilidad o valor por defecto)' end as estado
from esperado e
full outer join real r on r.columna = e.columna
where e.huella is distinct from r.huella
order by 2, 1;
